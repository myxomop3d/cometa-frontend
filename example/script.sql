BEGIN;

-- ---------------------------------------------------------------------------
-- 1. Create tables
-- ---------------------------------------------------------------------------

CREATE TABLE item (
    id          INTEGER PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    status      VARCHAR(3)   NOT NULL CHECK (status IN ('ON', 'OFF')),
    date        DATE         NOT NULL,
    count       INTEGER      NOT NULL
);

CREATE TABLE thing (
    id          INTEGER PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    status      VARCHAR(3)   NOT NULL CHECK (status IN ('ON', 'OFF')),
    date        DATE         NOT NULL,
    count       INTEGER      NOT NULL
);

CREATE TABLE box (
    id          INTEGER PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    object_code VARCHAR(50),
    shape       CHAR(1)      NOT NULL CHECK (shape IN ('O', 'X')),
    num         INTEGER      NOT NULL,
    item_id     INTEGER      REFERENCES item(id),
    old_item_id INTEGER      REFERENCES item(id),
    date_str    DATE         NOT NULL,
    checkbox    BOOLEAN      NOT NULL DEFAULT FALSE,
    tags        TEXT[]        NOT NULL DEFAULT '{}'
);

-- Many-to-many: box <-> things
CREATE TABLE box_thing (
    box_id   INTEGER NOT NULL REFERENCES box(id),
    thing_id INTEGER NOT NULL REFERENCES thing(id),
    PRIMARY KEY (box_id, thing_id)
);

-- Many-to-many: box <-> old_things
CREATE TABLE box_old_thing (
    box_id   INTEGER NOT NULL REFERENCES box(id),
    thing_id INTEGER NOT NULL REFERENCES thing(id),
    PRIMARY KEY (box_id, thing_id)
);

